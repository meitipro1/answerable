"""Push the golden cases through real consensus on GenLayer Studio (Studionet).

For each case: a desk (opened once per worker) receives the question, replies
with the case text, and the asker calls judge(). Verdict, reason and the judge
transaction hash are written to eval/results.json and eval/results.md.

    python eval/run_golden.py                 # every case not yet recorded
    python eval/run_golden.py --only 4,5      # re-run tuned cases

Held-out cases (H1-H3) run once. If results.json already holds one, it is
never run again, whatever it said.
"""

import argparse
import datetime
import json
import sys
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from chain import (  # noqa: E402
    CHAIN_ID,
    EXPLORER,
    GEN,
    accounts,
    client,
    deployed_address,
    fund,
    log,
    ok,
    read,
    summary,
    write,
)

HERE = Path(__file__).resolve().parent
GOLDEN = json.loads((HERE / "golden.json").read_text(encoding="utf-8"))
RESULTS_JSON = HERE / "results.json"
RESULTS_MD = HERE / "results.md"
WORKERS = 3
LOCK = threading.Lock()


def load_results() -> dict:
    if RESULTS_JSON.exists():
        return json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
    return {"address": None, "runs": {}}


def tx_str(tx) -> str:
    return tx if isinstance(tx, str) else tx.hex()


def run_case(address: str, worker: int, case: dict) -> dict:
    names = (f"eval_desk_{worker}", f"eval_asker_{worker}")
    desk, asker = (accounts(*names)[n] for n in names)
    cd, ca = client(desk), client(asker)
    tag = f"[{case['id']}]"
    try:
        read(cd, address, "get_desk", [desk.address])
    except Exception:  # noqa: BLE001 - no desk yet
        with LOCK:
            log(f"{tag} opening eval desk {worker}")
        tx, r = write(cd, desk, address, "open_desk",
                      [f"Golden desk {worker}", "", GEN // 100, 24, "Eval desk for the golden cases.", "eval"])
        if not ok(r):
            raise RuntimeError(f"open_desk failed: {summary(r)}")

    tx, r = write(ca, asker, address, "ask", [desk.address, case["question"], ""], value=GEN // 100)
    if not ok(r):
        raise RuntimeError(f"ask failed: {summary(r)}")
    # Each worker's desk takes one case at a time, so its newest open question is ours.
    listing = read(ca, address, "list_questions", [desk.address, "OPEN", 0, 1, "new"])
    qid = int(listing["items"][0]["id"])
    with LOCK:
        log(f"{tag} asked as question {qid}")

    tx, r = write(cd, desk, address, "reply", [qid, case["reply"]])
    if not ok(r):
        raise RuntimeError(f"reply failed: {summary(r)}")

    with LOCK:
        log(f"{tag} judging (validators are reading)")
    judge_tx, r = write(ca, asker, address, "judge", [qid])
    q = read(ca, address, "get_question", [qid, ""])
    status = q["status"]
    verdict = "DODGED" if status in ("DODGED_ONCE", "DODGED") else status
    if status == "REPLIED":
        verdict = "NO CONSENSUS"
    return {
        "id": case["id"],
        "held_out": case["held_out"],
        "expected": case["expected"],
        "verdict": verdict,
        "reason": q.get("reason", ""),
        "match": verdict == case["expected"],
        "qid": qid,
        "judge_tx": tx_str(judge_tx),
        "judge_receipt": summary(r),
        "ran_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    }


def write_markdown(results: dict) -> None:
    rows = [
        "# Golden cases, real consensus on GenLayer Studio",
        "",
        "Generated by `eval/run_golden.py`. Never edited by hand.",
        "",
        f"Contract `{results['address']}` on Studionet, chain {CHAIN_ID}, rubric {GOLDEN['rubric']}.",
        "",
        "| # | Expected | Verdict | Match | Reason | Judge tx |",
        "|---|---|---|---|---|---|",
    ]
    order = [c["id"] for c in GOLDEN["cases"]]
    for cid in order:
        r = results["runs"].get(cid)
        if not r:
            rows.append(f"| {cid} | | not run | | | |")
            continue
        mark = "yes" if r["match"] else "**no**"
        reason = r["reason"].replace("|", "\\|")
        tx = r["judge_tx"]
        rows.append(f"| {cid} | {r['expected']} | {r['verdict']} | {mark} | {reason} | [{tx[:10]}...]({EXPLORER}/tx/{tx}) |")
    tuned = [results["runs"][c] for c in order if c in results["runs"] and not results["runs"][c]["held_out"]]
    held = [results["runs"][c] for c in order if c in results["runs"] and results["runs"][c]["held_out"]]
    rows += [
        "",
        f"Tuned cases matching: {sum(r['match'] for r in tuned)} of {len(tuned)}. "
        f"Held-out cases matching: {sum(r['match'] for r in held)} of {len(held)}.",
        "",
        "H1 to H3 were written before the first run and run once. H3 is borderline on purpose.",
        "",
    ]
    RESULTS_MD.write_text("\n".join(rows), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default="", help="comma list of tuned case ids to (re)run")
    opts = parser.parse_args()
    address = deployed_address()
    results = load_results()
    if results["address"] not in (None, address):
        raise SystemExit(f"results.json belongs to {results['address']}, not {address}")
    results["address"] = address

    only = {x.strip() for x in opts.only.split(",") if x.strip()}
    todo = []
    for case in GOLDEN["cases"]:
        done = case["id"] in results["runs"]
        if case["held_out"] and done:
            continue  # held-out cases run exactly once
        if only and case["id"] not in only:
            continue
        if not only and done:
            continue
        if only and case["held_out"]:
            continue
        todo.append(case)
    if not todo:
        log("nothing to run")
        write_markdown(results)
        return

    funder = client(accounts("deployer")["deployer"])
    for w in range(WORKERS):
        for name, acct in accounts(f"eval_desk_{w}", f"eval_asker_{w}").items():
            fund(funder, acct.address, 20 * GEN, minimum=2 * GEN)
    log(f"running {len(todo)} cases on {address} with {WORKERS} workers")

    def job(i_case):
        i, case = i_case
        try:
            res = run_case(address, i % WORKERS, case)
        except Exception as exc:  # noqa: BLE001 - record and continue
            log(f"[{case['id']}] error: {exc}")
            return
        with LOCK:
            results["runs"][case["id"]] = res
            RESULTS_JSON.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
            write_markdown(results)
            log(f"[{case['id']}] {res['verdict']} (expected {res['expected']}) tx {res['judge_tx']}")

    # Cases sharing a worker run in order, workers run side by side.
    by_worker = [[(i, c) for i, c in enumerate(todo) if i % WORKERS == w] for w in range(WORKERS)]
    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        for lane in by_worker:
            pool.submit(lambda lane=lane: [job(x) for x in lane])
    write_markdown(results)
    log(f"wrote {RESULTS_MD}")


if __name__ == "__main__":
    main()
